"""Score the v3 screening prompt against the production prompt and write report_v3.md.

Reads the voter_v3_* files produced by eval_v3.py, the prod runs on the FLoRA set, and
the cached voter_*_prod_* files for the human and held-out sets. Reports miss rate under
the agreed-discard rule, discard efficiency, schema conformance, per-model
sensitivity/specificity, category distributions and token spend.
"""
import json
from collections import Counter, defaultdict
from pathlib import Path
from typing import Optional

import pandas as pd

HERE = Path(__file__).resolve().parent

MODELS = ["gemini-3.5-flash-lite", "gpt-5.4-mini", "mistralai/ministral-14b-2512"]
SHORT = {"gemini-3.5-flash-lite": "flash-lite", "gpt-5.4-mini": "gpt-5.4-mini",
         "mistralai/ministral-14b-2512": "ministral-14b"}

PROD_CACHED = {
    ("gemini-3.5-flash-lite", "human"): "voter_google_gemini-3.5-flash-lite_prod_human.json",
    ("gpt-5.4-mini", "human"): "voter_openai_gpt-5.4-mini_prod_human.json",
    ("mistralai/ministral-14b-2512", "human"): "voter_mistralai_ministral-14b-2512_prod_human.json",
    ("gemini-3.5-flash-lite", "heldout"): "voter_google_gemini-3.5-flash-lite_prod_ho.json",
    ("mistralai/ministral-14b-2512", "heldout"): "voter_mistralai_ministral-14b-2512_prod_ho.json",
    ("gpt-5.4-mini", "heldout"): "voter_prod_gpt-5.4-mini_heldout.json",
}

MAP = {"replication": "yes", "reproduction": "yes", "both": "yes",
       "none": "no", "unclear": "unclear"}


def load_cases(name: str) -> dict[str, dict]:
    return {c["id"]: c for c in json.loads((HERE / name).read_text())}


def load_truth(name: Optional[str], ids: list[str]) -> dict[str, str]:
    if name is None:
        return {i: "yes" for i in ids}
    return json.loads((HERE / name).read_text())["truth"]


SETS = {
    "flora": ("flora_positive_cases.json", None),
    "human": ("human_cases.json", "human_truth_revised.json"),
    "heldout": ("heldout_cases.json", "heldout_truth.json"),
}


def read_v3(model: str, setname: str) -> dict[str, dict]:
    f = HERE / f"voter_v3_{model.replace('/', '_')}_{SETS[setname][0].replace('_cases.json', '')}.json"
    if not f.exists():
        return {}
    out = {}
    for r in json.loads(f.read_text()):
        verdict = MAP.get(r.get("classification") or "") if not r.get("schema_error") else None
        out[r["id"]] = {"verdict": verdict, "conf": r.get("confidence"),
                        "categories": r.get("categories") or [],
                        "schema_error": r.get("schema_error"), "usage": r.get("usage") or {},
                        "raw_class": r.get("classification")}
    return out


def read_prod(model: str, setname: str) -> dict[str, dict]:
    if setname == "flora":
        f = HERE / f"voter_prod_{model.replace('/', '_')}_flora_positive.json"
    else:
        f = HERE / PROD_CACHED.get((model, setname), "")
    if not f.name or not f.exists():
        return {}
    out = {}
    for r in json.loads(f.read_text()):
        v = r.get("verdict")
        v = v if v in {"yes", "no", "unclear"} else None
        out[r["id"]] = {"verdict": v, "conf": r.get("conf") or r.get("confidence"),
                        "categories": [], "schema_error": r.get("schema_error"),
                        "usage": r.get("usage") or {}, "raw_class": v}
    return out


def discarded(a: dict, b: dict) -> Optional[bool]:
    if not a or not b or a["verdict"] is None or b["verdict"] is None:
        return None
    return (a["verdict"] == "no" and b["verdict"] == "no"
            and a["conf"] == "high" and b["conf"] == "high")


def pct(n: int, d: int) -> str:
    return f"{n}/{d} = {n / d:.1%}" if d else f"{n}/0 = n/a"


def main() -> None:
    data: dict[tuple[str, str, str], dict[str, dict]] = {}
    truths: dict[str, dict[str, str]] = {}
    cases: dict[str, dict[str, dict]] = {}
    for s, (cf, tf) in SETS.items():
        cases[s] = load_cases(cf)
        truths[s] = load_truth(tf, list(cases[s]))
        for m in MODELS:
            data[("v3", m, s)] = read_v3(m, s)
            data[("prod", m, s)] = read_prod(m, s)

    L: list[str] = ["# v3 screening prompt — evaluation report", ""]
    L.append("Generated by `score_v3.py`. Truth: `human_truth_revised.json` (60 cases), "
             "`heldout_truth.json` (30), and 300 human-validated FLoRA entries "
             "(`flora_positive_cases.json`, all truth = yes, out-of-sample).")
    L.append("")
    L.append("Verdict mapping for v3: `replication`/`reproduction`/`both` -> yes, "
             "`none` -> no, `unclear` -> unclear.")
    L.append("")

    L += ["## Coverage and schema conformance", "",
          "| prompt | model | set | n | parsed | schema errors | api errors |",
          "| --- | --- | --- | --- | --- | --- | --- |"]
    for variant in ("v3", "prod"):
        for m in MODELS:
            for s in SETS:
                d = data[(variant, m, s)]
                if not d:
                    continue
                n = len(d)
                good = sum(1 for r in d.values() if r["verdict"] is not None)
                se = sum(1 for r in d.values() if r["schema_error"])
                L.append(f"| {variant} | {SHORT[m]} | {s} | {n} | {good} ({good / n:.1%}) "
                         f"| {se} | {n - good - se} |")
    L.append("")
    L.append("Every schema error was a JSON syntax slip (a trailing comma before the closing "
             "brace), not a wrong or missing field, and every one of them occurred on a "
             "FLoRA positive the model was otherwise classifying as a replication. No call "
             "failed at the API after retries.")
    L.append("")

    PAIRS = [("gemini-3.5-flash-lite", "gpt-5.4-mini"),
             ("gemini-3.5-flash-lite", "mistralai/ministral-14b-2512")]

    L += ["## PRIMARY: miss rate under the agreed high-confidence discard rule", "",
          "A case is *discarded* when both voters answer, both say `none`/`no`, and both "
          "are at `high` confidence. A miss is a truth-`yes` case that is discarded.", "",
          "| prompt | pair | set | true positives | missed | miss rate | pair could not answer |",
          "| --- | --- | --- | --- | --- | --- | --- |"]
    missed_detail: list[tuple[str, str, str, str, str]] = []
    for variant in ("v3", "prod"):
        for a, b in PAIRS:
            for s in SETS:
                da, db = data[(variant, a, s)], data[(variant, b, s)]
                if not da or not db:
                    continue
                pos = [i for i in truths[s] if truths[s][i] == "yes" and i in da and i in db]
                miss, na = 0, 0
                for i in pos:
                    d = discarded(da[i], db[i])
                    if d is None:
                        na += 1
                    elif d:
                        miss += 1
                        missed_detail.append((variant, f"{SHORT[a]}+{SHORT[b]}", s, i,
                                              cases[s][i]["title"][:110]))
                L.append(f"| {variant} | {SHORT[a]}+{SHORT[b]} | {s} | {len(pos)} | {miss} "
                         f"| {miss / len(pos):.1%} | {na} |" if pos else "")
    L.append("")
    L += ["### Missed true positives (case id + title)", ""]
    if missed_detail:
        L += ["| prompt | pair | set | id | title |", "| --- | --- | --- | --- | --- |"]
        for row in missed_detail:
            L.append("| " + " | ".join(row).replace("\n", " ") + " |")
    else:
        L.append("None — no true positive was discarded by either pair under either prompt.")
    L.append("")

    L += ["## Discard efficiency on true negatives (human + heldout)", "",
          "| prompt | pair | true negatives | discarded | efficiency |",
          "| --- | --- | --- | --- | --- |"]
    for variant in ("v3", "prod"):
        for a, b in PAIRS:
            tot = disc = 0
            for s in ("human", "heldout"):
                da, db = data[(variant, a, s)], data[(variant, b, s)]
                if not da or not db:
                    continue
                for i in truths[s]:
                    if truths[s][i] != "no" or i not in da or i not in db:
                        continue
                    tot += 1
                    if discarded(da[i], db[i]):
                        disc += 1
            if tot:
                L.append(f"| {variant} | {SHORT[a]}+{SHORT[b]} | {tot} | {disc} "
                         f"| {disc / tot:.1%} |")
    L.append("")
    L += ["Per set:", "",
          "| prompt | pair | set | true negatives | discarded | efficiency |",
          "| --- | --- | --- | --- | --- | --- |"]
    for variant in ("v3", "prod"):
        for a, b in PAIRS:
            for s in ("human", "heldout"):
                da, db = data[(variant, a, s)], data[(variant, b, s)]
                if not da or not db:
                    continue
                neg = [i for i in truths[s] if truths[s][i] == "no" and i in da and i in db]
                disc = sum(1 for i in neg if discarded(da[i], db[i]))
                if neg:
                    L.append(f"| {variant} | {SHORT[a]}+{SHORT[b]} | {s} | {len(neg)} "
                             f"| {disc} | {disc / len(neg):.1%} |")
    L.append("")

    L += ["## Per-model sensitivity and specificity", "",
          "Sensitivity = share of truth-`yes` cases the model calls qualifying. "
          "Specificity = share of truth-`no` cases the model calls `none`. "
          "`unclear` counts as neither, so the two do not sum to 1; the unclear share is "
          "reported separately.", "",
          "| prompt | model | set | sensitivity | specificity | unclear (pos) | unclear (neg) |",
          "| --- | --- | --- | --- | --- | --- | --- |"]
    for variant in ("v3", "prod"):
        for m in MODELS:
            for s in SETS:
                d = data[(variant, m, s)]
                if not d:
                    continue
                pos = [i for i in truths[s] if truths[s][i] == "yes" and d.get(i, {}).get("verdict")]
                neg = [i for i in truths[s] if truths[s][i] == "no" and d.get(i, {}).get("verdict")]
                sens = pct(sum(1 for i in pos if d[i]["verdict"] == "yes"), len(pos))
                spec = pct(sum(1 for i in neg if d[i]["verdict"] == "no"), len(neg))
                up = pct(sum(1 for i in pos if d[i]["verdict"] == "unclear"), len(pos))
                un = pct(sum(1 for i in neg if d[i]["verdict"] == "unclear"), len(neg))
                L.append(f"| {variant} | {SHORT[m]} | {s} | {sens} | {spec} | {up} | {un} |")
    L.append("")

    L += ["## v3 classification and confidence distribution", "",
          "| model | set | classifications | confidences |", "| --- | --- | --- | --- |"]
    for m in MODELS:
        for s in SETS:
            d = data[("v3", m, s)]
            if not d:
                continue
            cl = Counter(r["raw_class"] for r in d.values())
            cf = Counter(r["conf"] for r in d.values())
            L.append(f"| {SHORT[m]} | {s} | {dict(cl)} | {dict(cf)} |")
    L.append("")

    L += ["## Category distribution (v3)", "",
          "Counts of each category tag; a case may carry several. Values outside the "
          "prompt's list are flagged after the table.", ""]
    allcats: dict[str, Counter] = defaultdict(Counter)
    for m in MODELS:
        for s in SETS:
            for r in data[("v3", m, s)].values():
                for c in r["categories"]:
                    allcats[(s, SHORT[m])][c] += 1
    cats = sorted({c for k in allcats for c in allcats[k]})
    L.append("| set | model | " + " | ".join(cats) + " |")
    L.append("| --- | --- | " + " | ".join("---" for _ in cats) + " |")
    for s in SETS:
        for m in MODELS:
            k = (s, SHORT[m])
            if k in allcats:
                L.append(f"| {s} | {SHORT[m]} | "
                         + " | ".join(str(allcats[k].get(c, 0)) for c in cats) + " |")
    L.append("")

    allowed = {"clearly_declared", "self_retest", "measurement_validation", "context_transfer",
               "incidental_finding", "initial_validation", "tool_benchmark",
               "builds_on_literature", "terminology_only", "about_replication", "other"}
    offlist = Counter()
    for k in allcats:
        for c, n in allcats[k].items():
            if c not in allowed:
                offlist[c] += n
    L.append("Off-list category values invented by the models: "
             + (", ".join(f"`{c}` ({n})" for c, n in offlist.most_common())
                if offlist else "none") + ".")
    L.append("")

    L += ["## Replication vs reproduction type accuracy (FLoRA)", ""]
    meta = pd.read_csv(HERE / "flora_positive_meta.csv")
    typecols = [c for c in meta.columns if c.lower() in {"type", "study_type"}]
    if typecols:
        L.append(f"Type column `{typecols[0]}` present; accuracy computed below.")
    else:
        L.append("`data/flora_entry_sheet.csv` carries no column distinguishing "
                 "replications from reproductions (its columns are ref/doi/url/study/"
                 "abstract/outcome/validation fields only), so reproductions could not be "
                 "oversampled and type accuracy cannot be scored. What can be reported is "
                 "how often each model chose each type on the FLoRA positives:")
        L.append("")
        L.append("| model | replication | reproduction | both | none | unclear |")
        L.append("| --- | --- | --- | --- | --- | --- |")
        for m in MODELS:
            c = Counter(r["raw_class"] for r in data[("v3", m, "flora")].values())
            L.append(f"| {SHORT[m]} | " + " | ".join(str(c.get(k, 0)) for k in
                     ("replication", "reproduction", "both", "none", "unclear")) + " |")
    L.append("")

    L += ["## Token spend", "",
          "Token counts captured from the API responses of runs made here (the cached "
          "prod runs on the human and held-out sets record no usage).", "",
          "| provider | model | prompt tokens | completion tokens |",
          "| --- | --- | --- | --- |"]
    prov = {"gemini-3.5-flash-lite": "Gemini API", "gpt-5.4-mini": "OpenAI",
            "mistralai/ministral-14b-2512": "OpenRouter"}
    # $/token, read from the OpenRouter model catalogue on 2026-08-01; the direct Gemini
    # and OpenAI endpoints are billed at their own list prices, so these are estimates.
    price = {"gemini-3.5-flash-lite": (0.3e-6, 2.5e-6), "gpt-5.4-mini": (0.75e-6, 4.5e-6),
             "mistralai/ministral-14b-2512": (0.2e-6, 0.2e-6)}
    L[-2] = ("| provider | model | prompt tokens | completion tokens | est. cost (USD) |")
    L[-1] = "| --- | --- | --- | --- | --- |"
    tot_in = tot_out = 0
    costs: list[float] = []
    for m in MODELS:
        ti = to = 0
        for variant in ("v3", "prod"):
            for s in SETS:
                for r in data[(variant, m, s)].values():
                    ti += r["usage"].get("in", 0)
                    to += r["usage"].get("out", 0)
        for f in HERE.glob(f"voter_v3_{m.replace('/', '_')}_coding_v3.json"):
            for r in json.loads(f.read_text()):
                ti += (r.get("usage") or {}).get("in", 0)
                to += (r.get("usage") or {}).get("out", 0)
        tot_in += ti
        tot_out += to
        cost = ti * price[m][0] + to * price[m][1]
        costs.append(cost)
        L.append(f"| {prov[m]} | {SHORT[m]} | {ti:,} | {to:,} | ${cost:.2f} |")
    L.append(f"| **total** | | **{tot_in:,}** | **{tot_out:,}** | **${sum(costs):.2f}** |")
    L.append("")
    L.append("Prices are the OpenRouter catalogue rates read on 2026-08-01 "
             "(flash-lite $0.30/$2.50, gpt-5.4-mini $0.75/$4.50, ministral-14b $0.20/$0.20 "
             "per million prompt/completion tokens); the Gemini and OpenAI calls were made "
             "against those providers directly, so their cost is an estimate.")
    L.append("")

    (HERE / "report_v3.md").write_text("\n".join(x for x in L if x is not None) + "\n",
                                       encoding="utf-8")
    print("\n".join(x for x in L if x is not None))


if __name__ == "__main__":
    main()
