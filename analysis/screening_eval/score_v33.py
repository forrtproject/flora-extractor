"""Score prompt_v33 against prompt_v32 on the corrected truth labels, write report_v33.md.

v3.3 is v3.2 plus one sentence in WHAT QUALIFIES: partial overlap with the original's data
does not disqualify a re-test. The question this script answers is whether that sentence
costs any hard-negative throughput or lets a settled positive through the gate.

Both prompts are scored over the two SHIPPED voters (flash-lite + gpt-5.4-mini) under the
SHIPPED gate `screen_gate()` (G-softqual), with G-strict alongside for continuity with
`report_v32.md`. Offline: reads the voter_v32_* and voter_v33_* result files here.
"""
import json
from collections import Counter
from pathlib import Path
from typing import Optional

HERE = Path(__file__).resolve().parent

FL = "gemini-3.5-flash-lite"
GPT = "gpt-5.4-mini"
MODELS = [FL, GPT]
SHORT = {FL: "flash-lite", GPT: "gpt-5.4-mini"}

MAP = {"replication": "yes", "reproduction": "yes", "both": "yes",
       "none": "no", "unclear": "unclear"}

SETS = {
    "flora": ("flora_positive_cases.json", None, "flora_positive"),
    "human": ("human_cases.json", "human_truth_v32.json", "human"),
    "heldout": ("heldout_cases.json", "heldout_truth_v32.json", "heldout"),
}

PENDING = {"F140"}
TAGS = ("v32", "v33")

PRICE = {FL: (0.3e-6, 2.5e-6), GPT: (0.75e-6, 4.5e-6)}
PROV = {FL: "Gemini API", GPT: "OpenAI"}


def load_cases(name: str) -> dict[str, dict]:
    return {c["id"]: c for c in json.loads((HERE / name).read_text())}


def read(tag: str, model: str, stem: str) -> dict[str, dict]:
    f = HERE / f"voter_{tag}_{model.replace('/', '_')}_{stem}.json"
    if not f.exists():
        return {}
    out = {}
    for r in json.loads(f.read_text()):
        bad = bool(r.get("schema_error")) or bool(r.get("error"))
        raw = r.get("confident")
        confident = raw if isinstance(raw, bool) else None
        out[r["id"]] = {"verdict": None if bad else MAP.get(r.get("classification") or ""),
                        "confident": None if bad else confident,
                        "raw_class": r.get("classification"),
                        "cats": [str(c) for c in (r.get("categories") or [])],
                        "schema_error": r.get("schema_error"), "error": r.get("error"),
                        "usage": r.get("usage") or {}}
    return out


def g_strict(recs: list[Optional[dict]]) -> bool:
    """Every voter answers `none` and every voter is confident."""
    if any(r is None or r["verdict"] is None for r in recs):
        return False
    return all(r["verdict"] == "no" and r["confident"] is True for r in recs)


def g_softqual(recs: list[Optional[dict]]) -> bool:
    """The shipped gate — `screen_gate()` in shared/llm_client.py, transcribed.

    Discard when every vote is `none` at any confidence, or when at least one voter
    said `none` confidently and every other vote is qualifying-or-unclear at
    `confident: false`.
    """
    if any(r is None or r["verdict"] is None for r in recs):
        return False
    is_none = [r["verdict"] == "no" for r in recs]
    if all(is_none):
        return True
    if not any(n and r["confident"] for n, r in zip(is_none, recs)):
        return False
    return all(n or (r["verdict"] in ("yes", "unclear") and r["confident"] is False)
               for n, r in zip(is_none, recs))


GATES = [("G-softqual (shipped)", g_softqual), ("G-strict", g_strict)]


def pct(n: int, d: int) -> str:
    return f"{n}/{d} = {n / d:.1%}" if d else "n/a"


def main() -> None:
    cases = {s: load_cases(cf) for s, (cf, _, _) in SETS.items()}
    truth = {}
    for s, (_, tf, _) in SETS.items():
        truth[s] = ({i: "yes" for i in cases[s]} if tf is None
                    else json.loads((HERE / tf).read_text())["truth"])

    data = {(t, m, s): read(t, m, SETS[s][2])
            for t in TAGS for m in MODELS for s in SETS}
    missing = [k for k, v in data.items() if not v]
    if missing:
        raise SystemExit(f"missing result files: {missing}")

    L: list[str] = ["# prompt_v33 vs prompt_v32 — the partial-overlap clause", ""]
    L.append("Generated by `score_v33.py`. `prompt_v33.txt` is `prompt_v32.txt` with one "
             "sentence added to WHAT QUALIFIES (item 7, partial data overlap): sharing some "
             "observations with the original does not disqualify a re-test that extends the "
             "original sample, adds a later wave, or partially overlaps the original data, "
             "when checking the earlier finding is an aim of the paper. Nothing else in the "
             "prompt changed — same schema, same categories, same confidence rules.")
    L.append("")
    L.append("Scored over the two **shipped** voters, `gemini-3.5-flash-lite` and "
             "`gpt-5.4-mini`, against the corrected labels: `human_truth_v32.json` "
             "(60 cases: 50 `no`, 10 `yes`), `heldout_truth_v32.json` (30: 20 `no`, 10 "
             "`yes`) and the 300 FLoRA entries in `flora_positive_cases.json` (all `yes`) — "
             "320 positives, 70 hard negatives.")
    L.append("")
    L.append("The primary gate is the shipped one, **G-softqual** (`screen_gate()` in "
             "`shared/llm_client.py`, transcribed in this script): discard when every vote is "
             "`none` at any confidence, or when one voter said `none` confidently and every "
             "other vote is qualifying-or-unclear at `confident: false`. **G-strict** (all "
             "`none`, all confident) is reported alongside for continuity with "
             "`report_v32.md`. `F140` is an adjudication-pending FLoRA entry and is counted "
             "apart from the settled misses. A schema or API error counts as no answer, so it "
             "can never contribute to a discard.")
    L.append("")
    L.append("These cases are derivation data (see `README.md`), so every number is in-sample. "
             "The v3.2 columns are the checked-in `voter_v32_*` files, not a re-run.")
    L.append("")

    hard_neg = [(s, i) for s in ("human", "heldout")
                for i in cases[s] if truth[s].get(i) == "no"]

    # ---------------------------------------------------------------- headline
    L += ["## Headline — v32 vs v33, shipped voter pair", "",
          f"Hard-negative pool: {len(hard_neg)} corrected true negatives "
          f"({sum(1 for s, _ in hard_neg if s == 'human')} human + "
          f"{sum(1 for s, _ in hard_neg if s == 'heldout')} held-out).", "",
          "| gate | prompt | settled misses | pending (F140) | hard-neg discard |",
          "| --- | --- | --- | --- | --- |"]
    for gname, gate in GATES:
        for t in TAGS:
            miss, pend = [], []
            for s in SETS:
                for i in cases[s]:
                    if truth[s].get(i) != "yes":
                        continue
                    if gate([data[(t, m, s)].get(i) for m in MODELS]):
                        (pend if i in PENDING else miss).append(f"{s}:{i}")
            hn = sum(1 for s, i in hard_neg
                     if gate([data[(t, m, s)].get(i) for m in MODELS]))
            L.append(f"| {gname} | {t} | {len(miss)} | {len(pend)} | "
                     f"{hn}/{len(hard_neg)} = {hn / len(hard_neg):.1%} |")
    L.append("")

    # ---------------------------------------------------------------- misses per set
    L += ["## 1. Miss rate per case set", "",
          "A miss is a corrected truth-`yes` case the voter pair discards.", "",
          "| gate | prompt | set | positives | settled misses | miss rate | pending | "
          "pair could not answer |",
          "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    miss_detail: list[tuple[str, ...]] = []
    for gname, gate in GATES:
        for t in TAGS:
            for s in SETS:
                pos = [i for i in cases[s] if truth[s].get(i) == "yes"]
                miss = pend = na = 0
                for i in pos:
                    recs = [data[(t, m, s)].get(i) for m in MODELS]
                    if any(r is None or r["verdict"] is None for r in recs):
                        na += 1
                        continue
                    if gate(recs):
                        if i in PENDING:
                            pend += 1
                        else:
                            miss += 1
                        miss_detail.append((gname, t, s, i,
                                            "PENDING" if i in PENDING else "settled",
                                            cases[s][i].get("title", "")[:110]
                                            .replace("\n", " ").replace("|", "/")))
                L.append(f"| {gname} | {t} | {s} | {len(pos)} | {miss} "
                         f"| {miss / len(pos):.1%} | {pend} | {na} |")
    L.append("")
    L += ["### Every discarded positive (case id + title)", ""]
    if miss_detail:
        L += ["| gate | prompt | set | id | status | title |",
              "| --- | --- | --- | --- | --- | --- |"]
        L += ["| " + " | ".join(row) + " |" for row in miss_detail]
    else:
        L.append("None — no corrected true positive was discarded under either prompt by "
                 "either gate.")
    L.append("")

    # ---------------------------------------------------------------- discard rate
    L += ["## 2. Discard rate on the corrected hard-negative pool", "",
          "| gate | prompt | set | true negatives | discarded | rate |",
          "| --- | --- | --- | --- | --- | --- |"]
    for gname, gate in GATES:
        for t in TAGS:
            for s in ("human", "heldout"):
                neg = [i for i in cases[s] if truth[s].get(i) == "no"]
                d = sum(1 for i in neg if gate([data[(t, m, s)].get(i) for m in MODELS]))
                L.append(f"| {gname} | {t} | {s} | {len(neg)} | {d} | {d / len(neg):.1%} |")
    L.append("")

    # ---------------------------------------------------------- 3. what moved
    L += ["## 3. Every case whose gate outcome moved", "",
          "The clause is meant to keep overlapping-sample re-tests. This table is every "
          "case where the shipped gate's verdict differs between v3.2 and v3.3.", ""]
    moved: list[str] = []
    for s in SETS:
        for i in cases[s]:
            a = g_softqual([data[("v32", m, s)].get(i) for m in MODELS])
            b = g_softqual([data[("v33", m, s)].get(i) for m in MODELS])
            if a == b:
                continue
            cells = " | ".join(
                f"{(data[(t, m, s)].get(i) or {}).get('raw_class')}@"
                f"{(data[(t, m, s)].get(i) or {}).get('confident')}"
                for m in MODELS for t in TAGS)
            moved.append(f"| {i} | {s} | {truth[s].get(i)} | {cells} | "
                         f"{'DISC' if a else 'kept'}->{'DISC' if b else 'kept'} | "
                         f"{cases[s][i].get('title', '')[:80].replace('|', '/')} |")
    if moved:
        L += ["| id | set | truth | "
              + " | ".join(f"{SHORT[m]} v32 | {SHORT[m]} v33" for m in MODELS)
              + " | gate v32 -> v33 | title |",
              "| --- | --- | --- | " + " | ".join("---" for _ in range(2 * len(MODELS) + 2))
              + " |"] + moved
    else:
        L.append("None — the shipped gate reaches the same verdict on all 390 cases under "
                 "both prompts.")
    L.append("")

    # ------------------------------------------------- 4. per-model verdict changes
    L += ["### Per-model verdict changes (any direction)", "",
          "| model | set | n | verdict changed | of which no -> qualifying | "
          "qualifying -> no | confident flipped |",
          "| --- | --- | --- | --- | --- | --- | --- |"]
    for m in MODELS:
        for s in SETS:
            a, b = data[("v32", m, s)], data[("v33", m, s)]
            ids = [i for i in cases[s] if i in a and i in b]
            ch = [i for i in ids if a[i]["verdict"] != b[i]["verdict"]]
            up = sum(1 for i in ch if a[i]["verdict"] == "no" and b[i]["verdict"] == "yes")
            dn = sum(1 for i in ch if a[i]["verdict"] == "yes" and b[i]["verdict"] == "no")
            cf = sum(1 for i in ids if a[i]["confident"] != b[i]["confident"])
            L.append(f"| {SHORT[m]} | {s} | {len(ids)} | {len(ch)} | {up} | {dn} | {cf} |")
    L.append("")

    # ---------------------------------------------------------------- 5. sens/spec
    L += ["## 4. Per-model sensitivity and specificity (corrected labels)", "",
          "Sensitivity = share of truth-`yes` cases the model calls qualifying; specificity "
          "= share of truth-`no` cases it calls `none`. `unclear` counts as neither.", "",
          "| prompt | model | set | sensitivity | specificity | unclear (pos) | unclear (neg) |",
          "| --- | --- | --- | --- | --- | --- | --- |"]
    for t in TAGS:
        for m in MODELS:
            for s in SETS:
                d = data[(t, m, s)]
                pos = [i for i in cases[s]
                       if truth[s].get(i) == "yes" and d.get(i, {}).get("verdict")]
                neg = [i for i in cases[s]
                       if truth[s].get(i) == "no" and d.get(i, {}).get("verdict")]
                L.append(f"| {t} | {SHORT[m]} | {s} "
                         f"| {pct(sum(1 for i in pos if d[i]['verdict'] == 'yes'), len(pos))} "
                         f"| {pct(sum(1 for i in neg if d[i]['verdict'] == 'no'), len(neg))} "
                         f"| {pct(sum(1 for i in pos if d[i]['verdict'] == 'unclear'), len(pos))} "
                         f"| {pct(sum(1 for i in neg if d[i]['verdict'] == 'unclear'), len(neg))} |")
    L.append("")

    L += ["### Schema conformance", "",
          "| prompt | model | set | n | parsed | schema errors | api errors |",
          "| --- | --- | --- | --- | --- | --- | --- |"]
    for t in TAGS:
        for m in MODELS:
            for s in SETS:
                d = data[(t, m, s)]
                n = len(d)
                good = sum(1 for r in d.values() if r["verdict"] is not None)
                se = sum(1 for r in d.values() if r["schema_error"])
                ae = sum(1 for r in d.values() if r["error"])
                L.append(f"| {t} | {SHORT[m]} | {s} | {n} | {good} ({good / n:.1%}) "
                         f"| {se} | {ae} |")
    L.append("")
    se_kinds: Counter = Counter()
    for m in MODELS:
        for s in SETS:
            for r in data[("v33", m, s)].values():
                if r["schema_error"]:
                    se_kinds[f"{SHORT[m]}:{r['schema_error']}"] += 1
    L.append("v33 schema errors by kind: "
             + (", ".join(f"`{k}` ({n})" for k, n in se_kinds.most_common())
                if se_kinds else "none — every response carried a boolean `confident`."))
    L.append("")

    L += ["### Classification mix and confidence per model and set", "",
          "| prompt | model | set | classifications | confident |",
          "| --- | --- | --- | --- | --- |"]
    for t in TAGS:
        for m in MODELS:
            for s in SETS:
                d = data[(t, m, s)]
                L.append(f"| {t} | {SHORT[m]} | {s} "
                         f"| {dict(Counter(r['raw_class'] for r in d.values()))} "
                         f"| {dict(Counter(r['confident'] for r in d.values()))} |")
    L.append("")

    # ---------------------------------------------------------------- 6. tokens
    L += ["## 5. Token usage and estimated spend — the v3.3 run", "",
          "Counts read from the API responses of the v3.3 runs made here (390 cases per "
          "model: 300 FLoRA positives, 60 human, 30 held-out).", "",
          "| provider | model | v33 in | v33 out | est. cost |",
          "| --- | --- | --- | --- | --- |"]
    tot = 0.0
    t_in = t_out = 0
    for m in MODELS:
        ti = to = 0
        for s in SETS:
            for r in data[("v33", m, s)].values():
                ti += r["usage"].get("in", 0)
                to += r["usage"].get("out", 0)
        cost = ti * PRICE[m][0] + to * PRICE[m][1]
        tot += cost
        t_in += ti
        t_out += to
        L.append(f"| {PROV[m]} | {SHORT[m]} | {ti:,} | {to:,} | ${cost:.2f} |")
    L.append(f"| **total** | | **{t_in:,}** | **{t_out:,}** | **${tot:.2f}** |")
    L.append("")
    L.append("Prices are the OpenRouter catalogue rates read on 2026-08-01 (flash-lite "
             "$0.30/$2.50, gpt-5.4-mini $0.75/$4.50 per million prompt/completion tokens); "
             "both calls went to the providers directly, so the cost is an estimate.")
    L.append("")

    (HERE / "report_v33.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
